# This script demonstrates basic variables and data types in Python.

# String
name = "Alice"

# Integer
age = 30

# Float
height = 5.7

# Boolean
is_student = False

# Printing the variables
print(f"Name: {name}")
print(f"Age: {age}")
print(f"Height: {height}")
print(f"Is Student: {is_student}")

# Basic math operations
birth_year = 2026 - age
print(f"{name} was born around {birth_year}.")
